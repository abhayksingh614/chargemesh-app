/**
 * Returns pre-computed sorted array of all 36 States/UTs
 */
export const getAllStates = (): string[] => {
  return ALL_STATES;
};

/**
 * Returns all districts belonging to a specific state
 */
export const getDistrictsByState = (stateName: string): string[] => {
  if (!stateName) return [];
  const match = Object.keys(STATE_DISTRICT_DATA).find(
    (s) => s.toLowerCase() === stateName.toLowerCase()
  );
  if (!match || !STATE_DISTRICT_DATA[match]) return [];
  return STATE_DISTRICT_DATA[match];
};

/**
 * Returns all 719 districts with their parent state
 */
export const getAllDistrictsWithState = (): Array<{ district: string; state: string }> => {
  return ALL_DISTRICTS_WITH_STATE;
};

/**
 * Search districts across all states with autocomplete matching
 */
export const searchDistricts = (
  query: string,
  limit: number = 20
): Array<{ district: string; state: string }> => {
  if (!query || !query.trim()) return [];
  const q = query.toLowerCase().trim();
  const results: Array<{ district: string; state: string }> = [];
  for (const item of ALL_DISTRICTS_WITH_STATE) {
    if (item.district.toLowerCase().includes(q) || item.state.toLowerCase().includes(q)) {
      results.push(item);
      if (results.length >= limit) return results;
    }
  }
  return results;
};

/**
 * Verify if a given state name exists in the master database
 */
export const isValidState = (stateName: string): boolean => {
  if (!stateName) return false;
  return ALL_STATES.some((s) => s.toLowerCase() === stateName.toLowerCase());
};

/**
 * Verify if a district belongs to a state
 */
export const isValidDistrict = (stateName: string, districtName: string): boolean => {
  const districts = getDistrictsByState(stateName);
  return districts.some((d) => d.toLowerCase() === districtName.toLowerCase());
};
